#!/usr/bin/env python3
"""Fetch the researcher portraits from Wikimedia Commons, with credits.

Every file is reproduced unchanged under its own licence; the credits
written to CREDITS.md must be reproduced wherever the images are shown.
Only files hosted on Commons under a CC licence, or in the public
domain, are taken.
"""
import json, re, time, urllib.parse, urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "static" / "figures" / "portraits"
UA = {"User-Agent": "leancourse-course-notes/1.0 (teaching material; https://github.com/pfaffelh/leancourse)"}
WANT = {                       # slug -> Commons file
    "hales":     "File:Halescropped.jpg",
    "scholze":   "File:Peter Scholze 2014 cropped.jpg",
    "buzzard":   "File:Kevin Buzzard 1996 (headshot).jpg",
    "demoura":   "File:Leo de Moura P1210629.jpg",
    "viazovska": "File:Maryna Vazovska MFO 2013 crop.jpg",
    "gowers":    "File:William Timothy Gowers Oslo 2012.jpg",
    "green":     "File:Ben Green.jpg",
    "tao":       "File:Terence Tao at IPAM's Fireside Chat 2026 (50m16s) (cropped).jpg",
    "voevodsky": "File:VladimirVoevodsky.jpg",
    "frege":     "File:Young frege.jpg",
    "russell":   "File:Bertrand Russell in 1907.jpg",
    "hilbert":   "File:Hilbert.jpg",
    "godel":     "File:Kurt gödel.jpg",
    "turing":    "File:Alan Turing (1951) (crop).jpg",
    "debruijn":  "File:Nicolaas de Bruijn.jpg",
}

# Head-and-shoulders crops, for files that are not already portraits.
# A crop is a derivative work; CC BY-SA allows it, and CREDITS.md says so.
CROP = {"debruijn": (90, 20, 510, 440)}

def api(params, tries=5):
    url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(params)
    for i in range(tries):
        try:
            return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40))
        except urllib.error.HTTPError as e:
            if e.code == 429:
                time.sleep(15 * (i + 1)); continue
            raise
    raise RuntimeError("rate limited")

OUT.mkdir(parents=True, exist_ok=True)
res = api({"action":"query","format":"json","prop":"imageinfo",
           "iiprop":"url|extmetadata","iiurlwidth":"600",
           "titles":"|".join(WANT.values())})
by_title = {p["title"].replace("_", " "): p for p in res["query"]["pages"].values()}
rows = []
for slug, title in WANT.items():
    p = by_title.get(title.replace("_", " "))
    assert p and "imageinfo" in p, f"not found: {title}"
    ii = p["imageinfo"][0]; md = ii["extmetadata"]
    lic = md.get("LicenseShortName", {}).get("value", "?")
    # CC for the living, public domain for the historical portraits -- nothing else
    assert lic.lower().startswith(("cc", "public domain")), \
        f"{slug}: unexpected licence {lic}"
    author = " ".join(re.sub("<[^>]+>", " ", md.get("Artist", {}).get("value", "?")).split())
    data = urllib.request.urlopen(urllib.request.Request(ii["thumburl"], headers=UA), timeout=60).read()
    dest = OUT / f"{slug}.jpg"
    dest.write_bytes(data)
    if slug in CROP:
        from PIL import Image
        Image.open(dest).crop(CROP[slug]).save(dest, quality=88)
    rows.append((slug, author, lic, ii["descriptionurl"]))
    print(f"  {slug:10} {len(data)//1024:4d} kB  {lic:16} {author[:38]}")
    time.sleep(1.0)

PREAMBLE = """# Portrait credits

All images are from Wikimedia Commons and are reproduced unchanged under
the licence given. The historical portraits (frege, russell, hilbert, godel, turing) are
in the public domain. Five of them (viazovska, gowers, green, voevodsky,
debruijn) are
reduced-resolution files released by the MFO itself; their terms ask for
the form "Author's name, Archives of the Mathematisches Forschungsinstitut
Oberwolfach", which is what the chapter uses. The de Bruijn photograph is
cropped to head and shoulders; everything else is unchanged. Full-resolution or
unwatermarked MFO images may not be published without permission. The
attribution below must be reproduced wherever the images are shown.

"""

FOOTER = """
## Placeholders

`placeholder_*.png` are generated by `scripts/figures/portrait_placeholders.py`
for the people who have no freely licensed photograph: Georges Gonthier,
Johan Commelin, Patrick Massot, Floris van Doorn, Oliver Nash, Freddie
Manners and Alonzo Church.

They are silhouettes with initials, not invented likenesses. To replace one,
drop the real photograph in as `<surname>.jpg`, point the chapter at it and
add the credit line above; nothing else changes.

Photographs of Commelin and Nash exist on the Mathlib Initiative team page
and of Massot on his own homepage, but all are under default copyright --
permission has been requested.
"""

with (OUT / "CREDITS.md").open("w") as f:
    f.write(PREAMBLE)
    for slug, author, lic, url in rows:
        f.write(f"- `{slug}.jpg` -- {author}, {lic}, via Wikimedia Commons, <{url}>\n")
    f.write(FOOTER)
print("wrote", OUT / "CREDITS.md")
